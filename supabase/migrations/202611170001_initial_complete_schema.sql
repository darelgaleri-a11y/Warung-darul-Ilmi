-- Cari tanggal pengiriman aktif berikutnya.
-- Sengaja mulai dari BESOK: pesanan pada hari pengiriman masuk jadwal berikutnya.
create or replace function public.next_delivery_date()
returns date
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_timezone text;
  v_today date;
  v_date date;
  v_override boolean;
  v_weekday_active boolean;
  i integer;
begin
  select s.timezone into v_timezone
  from public.store_settings s
  where s.id = true;

  v_today := (now() at time zone coalesce(v_timezone, 'Asia/Jakarta'))::date;

  for i in 1..31 loop
    v_date := v_today + i;

    select d.is_delivery_day into v_override
    from public.delivery_date_overrides d
    where d.delivery_date = v_date;

    if found then
      if v_override then
        return v_date;
      end if;
    else
      select w.is_active into v_weekday_active
      from public.delivery_weekdays w
      where w.weekday = extract(dow from v_date)::smallint;

      if coalesce(v_weekday_active, false) then
        return v_date;
      end if;
    end if;
  end loop;

  raise exception 'Belum ada jadwal pengiriman aktif dalam 31 hari ke depan.';
end;
$$;

